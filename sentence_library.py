def extract_sensory_word(keywords: list) -> str:
    """VLM keywords 리스트에서 감각묘사 형용사 1개를 추출한다.
    매칭 실패 시 '맛있는' 반환.
    """
    for kw in keywords:
        for trigger, adjective in SENSORY_MAP.items():
            if trigger in str(kw):
                return adjective
    return "맛있는"


# ── 조사 처리 ────────────────────────────────────────────────
def has_batchim(word: str) -> bool:
    """마지막 글자에 받침이 있는지 확인한다."""
    if not word:
        return False
    last = word[-1]
    if '가' <= last <= '힣':
        return (ord(last) - 0xAC00) % 28 != 0
    return False


# {변수+조사} 형태의 조사 쌍 (받침O, 받침X)
_JOSA_PAIRS: dict[str, tuple[str, str]] = {
    "이에요":  ("이에요",  "예요"),
    "이야":    ("이야",    "야"),
    "은":      ("은",      "는"),
    "이":      ("이",      "가"),
    "을":      ("을",      "를"),
    "과":      ("과",      "와"),
    "으로":    ("으로",    "로"),
    "이랑":    ("이랑",    "랑"),
    "이고":    ("이고",    "고"),
    "아":      ("아",      "야"),
}


def fill_vars(template: str, **kwargs) -> str:
    """템플릿의 {변수} 및 {변수+조사}를 실제 값으로 치환한다.

    {메뉴명+이에요} 형태는 변수 값의 받침 유무에 따라 조사를 자동 선택한다.
    예) 메뉴명=마라탕  → 마라탕이에요
        메뉴명=꿔바로우 → 꿔바로우예요
    """
    import re

    # 1) {변수+조사} 패턴 먼저 처리
    def replace_josa(m: re.Match) -> str:
        var_name = m.group(1)
        josa_key = m.group(2)
        value    = str(kwargs.get(var_name, ""))
        if not value:
            return ""
        pair = _JOSA_PAIRS.get(josa_key)
        if pair:
            return value + (pair[0] if has_batchim(value) else pair[1])
        return value + josa_key  # 매핑 없으면 그냥 붙임

    josa_keys = "|".join(re.escape(k) for k in _JOSA_PAIRS)
    template = re.sub(rf"\{{(\w+)\+({josa_keys})\}}", replace_josa, template)

    # 2) 일반 {변수} 치환
    for key, value in kwargs.items():
        template = template.replace(f"{{{key}}}", str(value) if value else "")

    return template.strip()
